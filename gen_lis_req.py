def set_cjk(run, font=CJK):
    run.font.name = font
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn('w:eastAsia'), font)

def style_heading(level):
    h = doc.styles['Heading %d' % level]
    h.font.name = CJK_HEI
    h.font.color.rgb = NAVY
    h.font.size = Pt({1:16,2:13.5,3:12,4:11}[level])
    rpr = h.element.rPr
    rpr.rFonts.set(qn('w:eastAsia'), CJK_HEI)

for lv in (1,2,3,4):
    style_heading(lv)

# ---------- 工具函数 ----------
def P(text='', size=10.5, bold=False, color=None, align=None, italic=False, space_after=4, font=CJK):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.25
    if text:
        r = p.add_run(text)
        r.bold = bold
        r.italic = italic
        r.font.size = Pt(size)
        if color is not None:
            r.font.color.rgb = color
        set_cjk(r, font)
    return p

def H(text, level=1):
    h = doc.add_heading(text, level=level)
    return h

def bullet(text, lead=None, level=0):
    p = doc.add_paragraph(style='List Bullet' if level==0 else 'List Bullet 2')
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.2
    if lead:
        r = p.add_run(lead)
        r.bold = True
        r.font.size = Pt(10.5)
        set_cjk(r)
    r2 = p.add_run(text)
    r2.font.size = Pt(10.5)
    set_cjk(r2)
    return p

def shade_cell(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)

def set_cell(cell, text, bold=False, color=None, size=9.5, align=None, fill=None):
    cell.text = ''
    p = cell.paragraphs[0]
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.line_spacing = 1.1
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    if color is not None:
        r.font.color.rgb = color
    set_cjk(r)
    if fill:
        shade_cell(cell, fill)

def req_table(headers, rows, widths=None, header_fill='1a365d'):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        set_cell(hdr[i], h, bold=True, color=RGBColor(0xff,0xff,0xff), size=9.5,
                 align=WD_ALIGN_PARAGRAPH.CENTER, fill=header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            set_cell(cells[i], val, size=9.0)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def callout(title, text):
    t = doc.add_table(rows=1, cols=1)
    t.style = 'Table Grid'
    cell = t.rows[0].cells[0]
    shade_cell(cell, 'eef3fa')
    cell.text = ''
    p = cell.paragraphs[0]
    r = p.add_run('【'+title+'】 ')
    r.bold = True; r.font.size = Pt(9.5); r.font.color.rgb = NAVY; set_cjk(r)
    r2 = p.add_run(text)
    r2.font.size = Pt(9.5); set_cjk(r2)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)

def add_toc():
    p = doc.add_paragraph()
    run = p.add_run()
    fldStart = OxmlElement('w:fldChar'); fldStart.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-3" \\h \\z \\u'
    fldSep = OxmlElement('w:fldChar'); fldSep.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t'); t.text = '（打开文档后右键“更新域”以生成目录）'
    fldEnd = OxmlElement('w:fldChar'); fldEnd.set(qn('w:fldCharType'), 'end')
    run._r.append(fldStart); run._r.append(instr); run._r.append(fldSep); run._r.append(t); run._r.append(fldEnd)
    set_cjk(run)

