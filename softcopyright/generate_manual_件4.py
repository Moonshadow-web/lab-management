def set_cn(run, font="宋体", size=11, bold=False):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = bold
    r = run._element
    r.rPr.rFonts.set(qn("w:eastAsia"), font)


def heading(text, level=1):
    p = doc.add_heading(level=level)
    run = p.add_run(text)
    set_cn(run, "黑体", 14 if level == 1 else 12, bold=True)
    return p


def para(text, size=11, bold=False, indent=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Inches(0.3)
    run = p.add_run(text)
    set_cn(run, "宋体", size, bold)
    return p


def add_table(headers, rows, widths=None):
    """带边框表格，中文宋体 9pt"""
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        run = hdr[i].paragraphs[0].add_run(h)
        set_cn(run, "黑体", 9, bold=True)
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(v))
            set_cn(run, "宋体", 9)
    doc.add_paragraph()
    return t


def add_screenshot(img_path, caption):
    """插入真实截图 + 图题"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
