    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run("图：" + caption)
    set_cn(r, "宋体", 9)
    r.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    return p


